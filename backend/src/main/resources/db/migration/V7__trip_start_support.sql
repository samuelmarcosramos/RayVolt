CREATE TABLE trip_riders (
    id BIGINT PRIMARY KEY CHECK (id > 0),
    category VARCHAR(30) NOT NULL CHECK (category IN ('WORKER', 'SECURITY_GUARD', 'CONTRACTOR', 'VISITOR')),
    enabled BOOLEAN NOT NULL,
    valid_until DATE,
    CHECK (category NOT IN ('CONTRACTOR', 'VISITOR') OR valid_until IS NOT NULL)
);
ALTER TABLE trips ADD COLUMN rider_id BIGINT REFERENCES trip_riders(id);
CREATE INDEX trips_rider_id_idx ON trips(rider_id);

CREATE TABLE trip_policies (
    category VARCHAR(30) PRIMARY KEY,
    allowed_from TIME NOT NULL,
    allowed_until TIME NOT NULL,
    time_zone VARCHAR(80) NOT NULL,
    minimum_battery INTEGER NOT NULL CHECK (minimum_battery BETWEEN 0 AND 100),
    max_minutes INTEGER NOT NULL CHECK (max_minutes > 0),
    overtime_rate NUMERIC(12, 2) NOT NULL CHECK (overtime_rate >= 0)
);
CREATE TABLE trip_policy_types (
    category VARCHAR(30) NOT NULL REFERENCES trip_policies(category),
    scooter_type VARCHAR(40) NOT NULL,
    PRIMARY KEY (category, scooter_type)
);
CREATE TABLE trip_bookings (
    scooter_id BIGINT PRIMARY KEY REFERENCES scooters(id),
    rider_id BIGINT NOT NULL REFERENCES trip_riders(id),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX trip_bookings_rider_id_idx ON trip_bookings(rider_id);

CREATE TABLE deposit_accounts (
    rider_id BIGINT PRIMARY KEY REFERENCES trip_riders(id),
    available_balance NUMERIC(12, 2) NOT NULL CHECK (available_balance >= 0)
);
CREATE TABLE deposit_holds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id BIGINT NOT NULL REFERENCES trip_riders(id),
    trip_id BIGINT UNIQUE REFERENCES trips(id),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    held_at TIMESTAMP WITH TIME ZONE NOT NULL
);
