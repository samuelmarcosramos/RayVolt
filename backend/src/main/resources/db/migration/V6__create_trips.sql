CREATE TABLE trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scooter_id BIGINT NOT NULL REFERENCES scooters(id),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    start_hub_id BIGINT NOT NULL REFERENCES hubs(id),
    start_odometer_km DOUBLE PRECISION NOT NULL CHECK (start_odometer_km >= 0),
    max_minutes INTEGER NOT NULL CHECK (max_minutes > 0),
    overtime_rate NUMERIC(12, 2) NOT NULL CHECK (overtime_rate >= 0),
    ended_at TIMESTAMP WITH TIME ZONE,
    end_hub_id BIGINT REFERENCES hubs(id),
    end_lat DOUBLE PRECISION,
    end_lon DOUBLE PRECISION,
    km_ridden DOUBLE PRECISION CHECK (km_ridden >= 0),
    overtime_minutes BIGINT NOT NULL DEFAULT 0 CHECK (overtime_minutes >= 0),
    overtime_charge NUMERIC(12, 2),
    no_hub_charge NUMERIC(12, 2),
    CHECK (ended_at IS NULL OR ended_at >= started_at)
);
CREATE INDEX trips_scooter_id_idx ON trips(scooter_id);
